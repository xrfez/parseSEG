## Runs every tests/t*.nim file, compiled once. From the project root:
##
##   nim test
##   nim c -r tests/tfoo.nim                 # that test alone, no runner
##   nim c -r tests/tester.nim -- tfoo       # one test, through the runner
##   PARSESEG_TEST_SEPARATE=1 nim test      # the old way: compile each file
##   nim c -r tests/tester.nim -- --separate
##
## The checks of a test live in `proc main*()` and the file ends with
## `when isMainModule: main()`, so importing it runs nothing. The runner
## writes an aggregate program into the build cache (not a source file),
## compiles it once, and runs `alltests <name>` per test, each its own
## process. A `# test-separate: <reason>` line marks a file the runner
## compiles alone: its own defines, a libc interposition, or it must be
## the main module. `alltests --list` prints the aggregate's names.
##
## On Windows a file whose header holds a `## Not on Windows: <why>` line is
## left out (it uses POSIX calls the platform does not have), and a failing
## file does not stop the run: every file runs, every failure is listed at the
## end and the exit code is 1, so one run shows them all
## (`PARSESEG_TEST_KEEP_GOING=1` does that on any platform).

import std/[algorithm, os, osproc, strutils]

const
  SeparateMarker = "# test-separate:"
  NotWindowsMarker = "## Not on Windows:"
  keepGoing = defined(windows)

proc fatal(msg: string) = quit "FAILURE " & msg

proc markedSeparate(path: string): bool =
  ## True when `path` has a `# test-separate:` line. Seen failing with that
  ## line ignored: a marked file was compiled into the aggregate.
  for line in lines(path):
    if line.strip.startsWith(SeparateMarker): return true
  false

proc markedNotWindows(path: string): bool =
  ## True when `path` has a `## Not on Windows:` line (with a reason).
  for line in lines(path):
    if line.strip.startsWith(NotWindowsMarker): return true
  false

proc exec(cmd: string) =
  echo "Running: ", cmd
  if execShellCmd(cmd) != 0:
    if "alltests.nim" in cmd:
      echo "PARSESEG_TEST_SEPARATE=1 compiles every file alone"
    fatal cmd

proc tryExec(cmd: string): bool =
  ## Runs `cmd`; false when it failed (the caller lists it and goes on).
  echo "Running: ", cmd
  execShellCmd(cmd) == 0

# Forward the build mode, so `nim c -d:danger -r tests/tester.nim` tests danger
# builds, `-d:cpuV3` (tests/config.nims: x86-64-v3) so `nim testV3` tests
# the CPU target the CLI ships with, and `-d:parseSegNoMapGuard` (`nim
# testNoGuard`: no SIGBUS handler).
const mode =
  (when defined(danger): " -d:danger"
   elif defined(release): " -d:release"
   else: "") & (when defined(cpuV3): " -d:cpuV3" else: "") &
  (when defined(parseSegNoMapGuard): " -d:parseSegNoMapGuard" else: "") &
  (when defined(parseSegUnmapped): " -d:parseSegUnmapped" else: "") &
  (when defined(parseSegReadCacheStress): " -d:parseSegReadCacheStress" else: "")

proc nimString(s: string): string =
  result = "\""
  for c in s:
    if c == '\\' or c == '"': result.add '\\'
    result.add c
  result.add '"'

proc testFiles(testDir: string): seq[string] =
  for f in walkFiles(testDir / "t*.nim"):
    if f.extractFilename != "tester.nim" and not (defined(windows) and markedNotWindows(f)):
      result.add f
  result.sort()

proc writeCfg(dir, root: string) =
  ## Search paths the aggregate needs. It lives in the build cache, so it
  ## does not see `tests/config.nims` or the project's `nim.cfg`.
  var s = "switch(\"noNimblePath\")\n"
  s.add "switch(\"path\", " & nimString(root / "src") & ")\n"
  s.add "switch(\"path\", " & nimString(root / "tests") & ")\n"
  for line in lines(root / "nim.cfg"):
    let t = line.strip
    if t.startsWith("--path:"):
      var p = t["--path:".len .. ^1].strip(chars = {'"', ' '})
      s.add "switch(\"path\", " & nimString(root / p) & ")\n"
  s.add """
when defined(cpuV3) and defined(amd64):
  switch("passC", "-march=x86-64-v3")
"""
  writeFile(dir / "config.nims", s)

proc writeAggregate(dir: string, names: seq[string]) =
  var s = "## Generated by tests/tester.nim. Not a source file.\n\nimport std/os\n\n"
  for n in names:
    s.add "import " & n & " as m_" & n & "\n"
  s.add "\nproc listed*(): seq[string] =\n"
  for n in names:
    s.add "  result.add \"" & n & "\"\n"
  s.add "\nproc run*(name: string) =\n  case name\n"
  for n in names:
    s.add "  of \"" & n & "\": m_" & n & ".main()\n"
  s.add """  else:
    quit "unknown test: " & name

when isMainModule:
  let args = commandLineParams()
  if args.len == 1 and args[0] == "--list":
    for n in listed(): echo n
    quit 0
  if args.len != 1:
    quit "usage: alltests <name>|--list"
  run(args[0])
"""
  writeFile(dir / "alltests.nim", s)

proc checkMarkers(testDir: string) =
  let tmp = getTempDir() / "parseseg_marker_check.nim"
  writeFile(tmp, "# test-separate: reason\nproc main*() = discard\n")
  doAssert markedSeparate(tmp), "a marked file was not separate"
  writeFile(tmp, "## note\nproc main*() = discard\n")
  doAssert not markedSeparate(tmp), "an unmarked file was separate"
  writeFile(tmp, "## Not on Windows: a reason\nproc main*() = discard\n")
  doAssert markedNotWindows(tmp), "a Not on Windows file was not marked"
  writeFile(tmp, "## note\nproc main*() = discard\n")
  doAssert not markedNotWindows(tmp), "an unmarked file was marked"
  removeFile(tmp)
  doAssert markedNotWindows(testDir / "tcutshort.nim"), "tcutshort lost its Not on Windows line"
  for name in ["tcommitfail.nim", "tguardslot.nim", "tkeyfields.nim", "tprefetch.nim",
      "tblockedclose.nim", "tboundedclose.nim", "treadwait.nim", "tunmapped.nim",
      "tcutshort.nim"]:
    doAssert markedSeparate(testDir / name), name & " lost its test-separate line"

proc stem(path: string): string = path.extractFilename.changeFileExt("")

when isMainModule:
  let root = getCurrentDir()
  let testDir = root / "tests"
  checkMarkers(testDir)
  var wanted: seq[string] = @[]
  var separateAll = getEnv("PARSESEG_TEST_SEPARATE") == "1"
  for a in commandLineParams():
    if a == "--":
      discard
    elif a == "--separate":
      separateAll = true
    elif a.startsWith("-"):
      fatal "unknown option " & a
    else:
      wanted.add a
  let keepOn = keepGoing or getEnv("PARSESEG_TEST_KEEP_GOING") == "1"
  var files = testFiles(testDir)
  if wanted.len > 0:
    var picked: seq[string] = @[]
    for w in wanted:
      let name = if w.endsWith(".nim"): w else: w & ".nim"
      var found = ""
      for f in files:
        if f.extractFilename == name: found = f
      if found.len == 0: fatal "no such test: " & w
      picked.add found
    files = picked
  let cache = getTempDir() / ("parseseg_tests" & mode.replace(" -d:", "_"))
  createDir(cache)
  let compiler = getCurrentCompilerExe().quoteShell
  var aggregate: seq[string] = @[]
  var alone: seq[string] = @[]
  for f in files:
    if separateAll or markedSeparate(f): alone.add f
    else: aggregate.add f
  var bin = ""
  if aggregate.len > 0:
    # Every aggregable test, not only the names on the command line: one
    # compile, then a process per test.
    var names: seq[string] = @[]
    for f in testFiles(testDir):
      if not markedSeparate(f): names.add stem(f)
    writeCfg(cache, root)
    writeAggregate(cache, names)
    bin = cache / "alltests"
    exec compiler & " c --hints:off" & mode & " --outdir:" & quoteShell(cache) &
      " -o:" & quoteShell(bin) & " " & quoteShell(cache / "alltests.nim")
    let (listed, code) = execCmdEx(quoteShell(bin) & " --list")
    if code != 0: fatal "alltests --list"
    for n in names:
      if n notin listed.splitLines: fatal "alltests --list omitted " & n
  var failed: seq[string] = @[]
  for f in files:
    let ok =
      if f in alone:
        tryExec compiler & " c -r --hints:off" & mode & " --outdir:" & quoteShell(cache) &
          " " & quoteShell(f)
      else:
        tryExec quoteShell(bin) & " " & stem(f)
    if not ok:
      failed.add f.extractFilename
      if not keepOn: fatal f.extractFilename
  if failed.len > 0:
    echo "FAILED test files (", failed.len, " of ", files.len, "): ", failed.join(" ")
    quit 1

  echo "All test files completed."
