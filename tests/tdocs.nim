## The usage guides' examples (task 13.1): every fenced code block of
## `docs/guide/*.md` tagged `nim`, `c` or `python` is a complete program, and
## this test runs each one, so the guides cannot go stale.
##
## - `nim` blocks become one module each (`doc_<page>_<n>.nim`), imported in
##   page order by one generated main program: one compile for all of them.
##   Their top-level code runs at start-up, in that order.
## - `c` blocks are compiled against a freshly built C ABI library and the
##   committed `include/parseseg.h` (C99, `-Wall -Wextra -Werror`), then run.
## - `python` blocks run under `python3 -I` with the generated `parseseg`
##   package next to that library. A block that imports numpy is skipped
##   (with a message) when numpy is not installed.
##
## Every program runs in a fresh scratch directory that holds `SEG Spec`
## with a link to the sample files, so the examples use the same relative
## paths a reader would (`"SEG Spec/exampleFiles/63.sgd"`) and write their
## outputs next to themselves. Blocks tagged otherwise (`sh`, `text`) are
## not run. The C and Python blocks run on Linux and macOS only, and are
## skipped when `cc` or `python3` is missing.

import std/[algorithm, assertions, os, osproc, strutils]

const
  root = currentSourcePath().parentDir.parentDir
  guideDir = root / "docs" / "guide"

type
  Lang = enum langNim = "nim", langC = "c", langPython = "python"

  Snippet = object
    lang: Lang
    page: string ## Page name without `.md`.
    line: int    ## 1-based line of the opening fence.
    code: string

proc fail(msg: string) {.noreturn.} =
  quit "tdocs: " & msg

proc run(cmd: string, dir = ""): (string, int) =
  execCmdEx(cmd, workingDir = dir)

proc mustRun(cmd: string, what: string, dir = "") =
  let (o, code) = run(cmd, dir)
  if code != 0:
    echo o
    fail what & " failed: " & cmd
  if o.strip.len > 0: echo o.strip

proc snippets(path: string): seq[Snippet] =
  ## The `nim`, `c` and `python` blocks of the Markdown file `path`.
  let page = path.splitFile.name
  var inBlock = false
  var cur: Snippet
  var keep = false
  let lines = readFile(path).splitLines
  for i, line in lines:
    let s = line.strip
    if not inBlock and s.startsWith("```"):
      inBlock = true
      let info = s[3 .. ^1].strip
      keep = true
      case info
      of "nim": cur = Snippet(lang: langNim)
      of "c": cur = Snippet(lang: langC)
      of "python": cur = Snippet(lang: langPython)
      else: keep = false
      cur.page = page
      cur.line = i + 1
    elif inBlock and s == "```":
      inBlock = false
      if keep: result.add cur
    elif inBlock and keep:
      cur.code.add line & "\n"
  if inBlock: fail path & ": a code block is not closed"

proc ident(s: string): string =
  for c in s: result.add(if c in IdentChars: c else: '_')

proc newRunDir(base: string): string =
  ## A fresh scratch directory holding `SEG Spec/exampleFiles`.
  result = base / "run"
  removeDir(result)
  createDir(result / "SEG Spec")
  let samples = root / "SEG Spec" / "exampleFiles"
  when defined(posix):
    createSymlink(samples, result / "SEG Spec" / "exampleFiles")
  else:
    copyDir(samples, result / "SEG Spec" / "exampleFiles")

proc nimPaths(): string =
  ## The project's search paths, absolute, for a program outside the tree.
  result = " --noNimblePath --path:" & quoteShell(root / "src") &
    " --path:" & quoteShell(getCurrentCompilerExe().parentDir.parentDir / "dist" / "nimony" /
      "src" / "lib")
  for line in readFile(root / "nim.cfg").splitLines:
    let s = line.strip
    if s.startsWith("--path:"):
      result.add " --path:" & quoteShell(root / s["--path:".len .. ^1].strip(chars = {'"'}))

let tmp = getTempDir() / "parseseg_tdocs"
createDir(tmp)

var all: seq[Snippet]
var pages: seq[string]
for f in walkFiles(guideDir / "*.md"): pages.add f
pages.sort()
for f in pages: all.add snippets(f)
doAssert all.len > 0, "no examples found in " & guideDir

# ---------------------------------------------------------------------- Nim --
block nim_examples:
  let gen = tmp / "nim"
  removeDir(gen)
  createDir(gen)
  var main = "## Generated by tests/tdocs.nim: runs every Nim example of docs/guide.\n"
  var n = 0
  for s in all:
    if s.lang != langNim: continue
    inc n
    let name = "doc_" & ident(s.page) & "_" & $s.line
    writeFile(gen / name & ".nim", "# docs/guide/" & s.page & ".md, line " & $s.line & "\n" &
      s.code)
    main.add "import " & name & "\n"
  writeFile(gen / "docs_main.nim", main)
  let exe = gen / "docs_main".addFileExt(ExeExt)
  mustRun(getCurrentCompilerExe().quoteShell & " c --hints:off --warnings:off" & nimPaths() &
    " --nimcache:" & quoteShell(tmp / "nimcache") & " -o:" & quoteShell(exe) & " " &
    quoteShell(gen / "docs_main.nim"), "compiling the Nim examples")
  mustRun(quoteShell(exe), "running the Nim examples", newRunDir(tmp))
  echo "tdocs: ", n, " Nim examples ok"

# ------------------------------------------------------------- C and Python --
when defined(linux) or defined(macosx):
  const libName = when defined(macosx): "libparseseg.dylib" else: "libparseseg.so"
  let cc = findExe("cc")
  let py = findExe("python3")
  if cc.len == 0 and py.len == 0:
    echo "tdocs: no cc and no python3; C and Python examples skipped"
  else:
    let pkg = tmp / "module" / "parseseg"
    createDir(pkg)
    createDir(tmp / "gen" / "include")
    createDir(tmp / "gen" / "python" / "parseseg")
    mustRun(getCurrentCompilerExe().quoteShell & " c --hints:off --app:lib --noMain " &
      "--mm:atomicArc --threads:on -d:useMalloc -d:segCapi --nimcache:" &
      quoteShell(tmp / "libcache") & " -d:segBindingsDir=" & quoteShell(tmp / "gen") & " -o:" &
      quoteShell(pkg / libName) & " " & quoteShell(root / "src" / "parseSEG" / "bindings.nim"),
      "building the C ABI library")
    copyFile(root / "python" / "parseseg" / "__init__.py", pkg / "__init__.py")

    block c_examples:
      if cc.len == 0:
        echo "tdocs: no C compiler; C examples skipped"
        break c_examples
      let gen = tmp / "c"
      removeDir(gen)
      createDir(gen)
      var n = 0
      for s in all:
        if s.lang != langC: continue
        inc n
        let name = "doc_" & ident(s.page) & "_" & $s.line
        writeFile(gen / name & ".c", s.code)
        let exe = gen / name
        mustRun(cc & " -std=c99 -D_POSIX_C_SOURCE=200809L -Wall -Wextra -Werror -pedantic -I" &
          quoteShell(root / "include") & " -o " & quoteShell(exe) & " " &
          quoteShell(gen / name & ".c") & " -L" & quoteShell(pkg) & " -lparseseg -lpthread -lm" &
          " -Wl,-rpath," & quoteShell(pkg), "compiling " & s.page & ".md line " & $s.line)
        mustRun(quoteShell(exe), "running " & s.page & ".md line " & $s.line, newRunDir(tmp))
      echo "tdocs: ", n, " C examples ok"

    block python_examples:
      if py.len == 0:
        echo "tdocs: no python3; Python examples skipped"
        break python_examples
      let (_, noNumpy) = run(py & " -I -c " & quoteShell("import numpy"))
      let gen = tmp / "python"
      removeDir(gen)
      createDir(gen)
      var n, skipped = 0
      for s in all:
        if s.lang != langPython: continue
        if noNumpy != 0 and "import numpy" in s.code:
          inc skipped
          continue
        inc n
        let script = gen / ("doc_" & ident(s.page) & "_" & $s.line & ".py")
        writeFile(script, s.code)
        # -I ignores PYTHONPATH: the package directory is put on sys.path by a stub.
        mustRun(py & " -I -c " & quoteShell("import sys, runpy; sys.path.insert(0, sys.argv[1]); " &
          "runpy.run_path(sys.argv[2], run_name='__main__')") & " " &
          quoteShell(tmp / "module") & " " & quoteShell(script),
          "running " & s.page & ".md line " & $s.line, newRunDir(tmp))
      echo "tdocs: ", n, " Python examples ok",
        (if skipped > 0: " (" & $skipped & " need numpy, which is not installed: skipped)"
         else: "")
else:
  echo "tdocs: the C and Python examples run on Linux and macOS only for now"
